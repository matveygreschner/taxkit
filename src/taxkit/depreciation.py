_FIRST_YEAR_FRACTION = {"HY": 0.5, "Q1": 10.5 / 12, "Q2": 7.5 / 12, "Q3": 4.5 / 12, "Q4": 1.5 / 12}


def macrs_rates(recovery_class: int, convention: str = "HY", decimals: int = 2) -> Tuple[float, ...]:
    """Generate MACRS percentages: 200% DB (150% DB for 15/20-year) switching to
    straight line, with the given first-year convention."""
    factor = 1.5 if recovery_class >= 15 else 2.0
    life = float(recovery_class)
    f1 = _FIRST_YEAR_FRACTION[convention]
    remaining = 100.0
    elapsed = 0.0
    out = []
    year = 0
    while remaining > 1e-9:
        frac = f1 if year == 0 else 1.0
        left = life - elapsed
        if left <= 0:
            break
        db = remaining * factor / life * frac
        sl = remaining / left * frac if left >= frac else remaining
        dep = remaining if left <= frac else max(db, sl)
        dep = min(dep, remaining)
        out.append(dep)
        remaining -= dep
        elapsed += frac
        year += 1
    rounded = [round(x, decimals) for x in out]
    rounded[-1] = round(100.0 - sum(rounded[:-1]), decimals)
    return tuple(rounded)


def macrs_table(recovery_class: int, convention: str = "HY") -> Tuple[float, ...]:
    """Percentages (e.g. 20.0 means 20%) for each recovery year."""
    key = (convention, recovery_class)
    if key in PUB946:
        return PUB946[key]
    return macrs_rates(recovery_class, convention, 3 if recovery_class == 20 else 2)


def needs_mid_quarter(q4_cost: float, total_cost: float) -> bool:
    """Mid-quarter applies if > 40% of the year's personal property (excluding
    real property and Sec. 179 amounts) is placed in service in Q4."""
    return total_cost > 0 and q4_cost / total_cost > 0.40


def sec179_allowed(cost_placed_in_service: float, total_179_property_year: float, elected: float,
                   business_taxable_income: float | None = None, year: int = DEFAULT_YEAR) -> Tuple[float, float]:
    """Sec. 179: limit reduced $-for-$ above the phase-out threshold and limited to
    business taxable income (excess carries forward). Returns (deduction, carryforward)."""
    limit = max(0.0, param("sec179_limit", year) - max(0.0, total_179_property_year - param("sec179_phaseout", year)))
    amt = min(elected, cost_placed_in_service, limit)
    if business_taxable_income is None:
        return round(amt, 2), 0.0
    allowed = min(amt, max(0.0, business_taxable_income))
    return round(allowed, 2), round(amt - allowed, 2)


@dataclass
class ScheduleRow:
    year: int
    rate_pct: float
    depreciation: float
    accumulated: float
    ending_basis: float


@dataclass
class AssetDepreciation:
    cost: float
    sec179: float
    bonus: float
    macrs_basis: float
    first_year_total: float
    schedule: List[ScheduleRow]


def personal_property_schedule(cost: float, recovery_class: int, convention: str = "HY",
                               sec179: float = 0.0, bonus_pct: float = 0.0,
                               business_use_pct: float = 1.0, disposed_in_year: int | None = None,
                               disposal_quarter: int | None = None) -> AssetDepreciation:
    """Full schedule: cost x business-use -> Sec. 179 -> bonus on remainder -> MACRS on the rest.
    If disposed, the disposal year gets half (HY) or the mid-quarter fraction."""
    basis = cost * business_use_pct
    after179 = max(0.0, basis - sec179)
    bonus = after179 * bonus_pct
    macrs_basis = after179 - bonus
    rates = macrs_table(recovery_class, convention)
    rows, acc = [], sec179 + bonus
    for i, pct in enumerate(rates, start=1):
        dep = macrs_basis * pct / 100.0
        if disposed_in_year is not None and i > disposed_in_year:
            break
        if disposed_in_year is not None and i == disposed_in_year and i < len(rates):
            if convention == "HY":
                dep *= 0.5
            else:
                q = disposal_quarter or 4
                dep *= (q * 3 - 1.5) / 12
        acc += dep
        rows.append(ScheduleRow(i, pct, round(dep, 2), round(acc, 2), round(basis - acc, 2)))
    first = sec179 + bonus + (rows[0].depreciation if rows else 0.0)
    return AssetDepreciation(cost, sec179, round(bonus, 2), round(macrs_basis, 2), round(first, 2), rows)


def real_property_depreciation(cost_of_building: float, month_placed: int, residential: bool = True,
                               years: int = 3, month_disposed: int | None = None,
                               disposal_year: int | None = None) -> List[ScheduleRow]:
    """Straight-line, mid-month convention: 27.5 years (330 months) residential,
    39 years (468 months) nonresidential. Land is never depreciated."""
    months = 330 if residential else 468
    monthly = cost_of_building / months
    rows, acc = [], 0.0
    for y in range(1, years + 1):
        if y == 1:
            m = 12 - month_placed + 0.5
        else:
            m = 12.0
        if disposal_year is not None and y == disposal_year and month_disposed:
            m = month_disposed - 0.5 if y > 1 else month_disposed - month_placed
        dep = min(monthly * m, cost_of_building - acc)
        acc += dep
        rows.append(ScheduleRow(y, round(dep / cost_of_building * 100, 3), round(dep, 2), round(acc, 2),
                                round(cost_of_building - acc, 2)))
        if disposal_year is not None and y == disposal_year:
            break
    return rows


def startup_costs(total: float, months_in_first_year: int, year: int = DEFAULT_YEAR) -> Tuple[float, float]:
    """Deduct up to $5,000 (reduced $-for-$ over $50,000), amortize the rest over
    180 months. Returns (first-year deduction, annual amortization thereafter)."""
    immediate = max(0.0, min(total, param("startup_deduction", year) -
                             max(0.0, total - param("startup_phaseout", year))))
    rest = total - immediate
    monthly = rest / 180
    return round(immediate + monthly * months_in_first_year, 2), round(monthly * 12, 2)


def sec197_amortization(cost: float, months_in_first_year: int) -> Tuple[float, float]:
    """Sec. 197 intangibles (goodwill, covenants, etc.): 15 years straight-line."""
    monthly = cost / 180
    return round(monthly * months_in_first_year, 2), round(monthly * 12, 2)


def cost_depletion(adjusted_basis: float, units_sold: float, estimated_remaining_units: float) -> float:
    """Basis / remaining recoverable units x units sold."""
    return round(adjusted_basis / estimated_remaining_units * units_sold, 2) if estimated_remaining_units else 0.0


def percentage_depletion(gross_income: float, rate: float, taxable_income_before_depletion: float) -> float:
    """Statutory % of gross income, limited to 50% of taxable income before depletion."""
    return round(min(gross_income * rate, 0.5 * max(0.0, taxable_income_before_depletion)), 2)
